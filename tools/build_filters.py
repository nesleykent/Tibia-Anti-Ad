"""Build deterministic experimental subscriptions from historical site inputs."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXCLUDED = {"tibiopedia.pl", "tibiawiki.com.br"}


def scope_rule(rule, domain):
    """Constrain network rules and reject unsupported source forms."""
    if "##" in rule:
        domains, selector = rule.split("##", 1)
        if any(d != domain and not d.endswith("." + domain) for d in domains.split(",")):
            raise ValueError(f"Unexpected cosmetic scope: {rule}")
        if not selector.strip():
            raise ValueError("Empty selector")
        return rule
    if not rule.startswith(("||", "@@||")):
        raise ValueError(f"Unsupported filter: {rule}")
    pattern, separator, options = rule.partition("$")
    parts = options.split(",") if separator else []
    scopes = [part for part in parts if part.startswith("domain=")]
    # Existing scopes must agree with the source; never broaden them.
    if scopes and scopes != [f"domain={domain}"]:
        raise ValueError(f"Unexpected network scope: {rule}")
    if not scopes:
        parts.append(f"domain={domain}")
    return pattern + "$" + ",".join(parts)


def build(extended=False):
    lines = [
        "[Adblock Plus 2.0]",
        "! Title: Tibia Anti-Ad" + (" Extended" if extended else " Portable"),
        "! Description: Experimental site-scoped ads, tracking and annoyance filters",
        "! Homepage: https://github.com/nesleykent/Tibia-Anti-Ad",
        "! Expires: 1 day",
        "! Version: 2026.10.21.1",
        "! Status: Experimental; browser enforcement not certified",
        "! Excluded: tibiopedia.pl, tibiawiki.com.br (content-destruction risks)",
        "! Generated by tools/build_filters.py; edit filters/sources/sites instead.",
    ]
    seen = set()
    for source in sorted((ROOT / "filters/sources/sites").glob("*.txt")):
        domain = source.name.removesuffix(".txt")
        if domain in EXCLUDED:
            continue
        lines += ["", f"! Source: {domain}; see research/fansites/reports for limitations"]
        for raw in source.read_text(encoding="utf-8").splitlines():
            rule = raw.strip()
            if not rule or rule.startswith(("!", "[Adblock")):
                continue
            if not extended and ":has(" in rule:
                continue
            scoped = scope_rule(rule, domain)
            if scoped not in seen:
                lines.append(scoped)
                seen.add(scoped)
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    for extended, name in [(False, "anti-ad-tibia.txt"), (True, "anti-ad-tibia-extended.txt")]:
        output = ROOT / "filters/lists" / name
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(build(extended), encoding="utf-8")
        print(f"Built {output.relative_to(ROOT)}")
