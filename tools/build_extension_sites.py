"""Build the fansite part of the Tibia Anti-Ad extension from filters/sources/sites.

For each site input this writes, under extension/src/sites/:
- <domain>.json: a declarativeNetRequest ruleset (network rules scoped to the site);
- <domain>.css: the site's cosmetic rules, one CSS rule per selector, each gated by
  the site's settings switch (html:not([data-tibia-anti-ad-off~="<domain>"])).
It also writes sites.js (the list the settings use) and updates manifest.json:
the rulesets, the per-site content scripts (CSS plus the hand-written fixes in
sites/fixes/), the host permissions and the settings bridge matches.

Run after editing filters/sources/sites; tests check the committed output matches.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "filters/sources/sites"
EXTENSION = ROOT / "extension/src"
SITES = EXTENSION / "sites"
TWITCH_MATCH = "*://*.twitch.tv/*"

# Hand-written fixes that filters cannot express (ported from research/fansites/userscripts).
# world MAIN runs in the page at document_start; ISOLATED runs as a content script.
FIXES = {
    "tibiopedia.pl": [{"js": "sites/fixes/tibiopedia.pl.js", "world": "MAIN"}],
    "tibiawiki.com.br": [{"js": "sites/fixes/tibiawiki.com.br.js", "world": "MAIN"}],
    "guildstats.eu": [{"js": "sites/fixes/adsense-overlays.js", "world": "ISOLATED"},
                      {"css": "sites/fixes/guildstats.eu.css"}],
    "tibiamonk.com": [{"js": "sites/fixes/adsense-overlays.js", "world": "ISOLATED"},
                      {"css": "sites/fixes/tibiamonk.com.css"}],
    "tibiaring.com": [{"css": "sites/fixes/tibiaring.com.css"}],
}
# Sites whose fixes defuse an anti-adblock script that would otherwise blank the page.
PROTECTED = {"tibiopedia.pl", "tibiawiki.com.br"}

RESOURCE_TYPES = {"script": "script", "image": "image", "subdocument": "sub_frame"}
NETWORK = re.compile(r"^(@@)?\|\|([^$\s]+)(?:\$(.*))?$")


def ruleset_id(domain):
    return "site_" + re.sub(r"[^a-z0-9]", "_", domain)


def network_rule(rule, domain, rule_id):
    """Convert one ||host^$options filter into a DNR rule scoped to its site."""
    match = NETWORK.match(rule)
    if not match:
        raise ValueError(f"{domain}: unsupported network filter: {rule}")
    allow, pattern, options = match.groups()
    condition = {"urlFilter": "||" + pattern}
    types, domains = [], [domain]
    for option in filter(None, (options or "").split(",")):
        if option == "3p":
            condition["domainType"] = "thirdParty"
        elif option == "1p":
            condition["domainType"] = "firstParty"
        elif option in RESOURCE_TYPES:
            types.append(RESOURCE_TYPES[option])
        elif option.startswith("domain="):
            scopes = option.removeprefix("domain=").split("|")
            if any(s != domain and not s.endswith("." + domain) for s in scopes):
                raise ValueError(f"{domain}: scope outside the site: {rule}")
            domains = scopes
        else:
            raise ValueError(f"{domain}: unsupported option {option!r}: {rule}")
    if not pattern.isascii():
        raise ValueError(f"{domain}: non-ASCII pattern: {rule}")
    if types:
        condition["resourceTypes"] = types
    condition["domains"] = domains
    return {
        "id": rule_id,
        "priority": 2 if allow else 1,
        "action": {"type": "allow" if allow else "block"},
        "condition": condition,
    }


def matches(host):
    return [f"*://{host}/*", f"*://*.{host}/*"]


def parse(source):
    domain = source.name.removesuffix(".txt")
    rules, cosmetic = [], {}
    for raw in source.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith(("!", "[Adblock")):
            continue
        if "##" in line:
            scope, selector = line.split("##", 1)
            hosts = tuple(sorted(scope.split(",")))
            if any(h != domain and not h.endswith("." + domain) for h in hosts) or not selector.strip():
                raise ValueError(f"{domain}: unexpected cosmetic rule: {line}")
            if "#" in scope or selector.startswith(("+js", "?")):
                raise ValueError(f"{domain}: procedural or scriptlet rule: {line}")
            cosmetic.setdefault(hosts, [])
            if selector not in cosmetic[hosts]:
                cosmetic[hosts].append(selector)
            continue
        rule = network_rule(line, domain, len(rules) + 1)
        if rule["condition"] not in [r["condition"] for r in rules if r["action"] == rule["action"]]:
            rules.append(rule)
    return domain, rules, cosmetic


def css_for(domain, cosmetic):
    lines = [
        f"/* Generated by tools/build_extension_sites.py from filters/sources/sites/{domain}.txt; do not edit.",
        f"   Each rule is gated by the {domain} switch in the extension's settings. */",
    ]
    gate = f'html:not([data-tibia-anti-ad-off~="{domain}"])'
    for hosts, selectors in cosmetic.items():
        lines += ["", f"/* {', '.join(hosts)} */"]
        lines += [f"{gate} {selector} {{ display: none !important; }}" for selector in selectors]
    return "\n".join(lines) + "\n"


def build():
    SITES.mkdir(exist_ok=True)
    sites, rule_resources, scripts, hosts = [], [], [], []
    for source in sorted(SOURCES.glob("*.txt")):
        domain, rules, cosmetic = parse(source)
        (SITES / f"{domain}.json").write_text(json.dumps(rules, indent=2) + "\n", encoding="utf-8")
        (SITES / f"{domain}.css").write_text(css_for(domain, cosmetic), encoding="utf-8")
        rule_resources.append({"id": ruleset_id(domain), "enabled": True, "path": f"sites/{domain}.json"})
        hosts += matches(domain)
        # Cosmetic rules scoped to a subdomain are injected only there.
        for scope in sorted({h for group in cosmetic for h in group}):
            scripts.append({"matches": matches(scope), "css": [f"sites/{domain}.css"],
                            "css_origin": "user", "run_at": "document_start", "all_frames": True})
        for fix in FIXES.get(domain, []):
            if "css" in fix:
                scripts.append({"matches": matches(domain), "css": [fix["css"]],
                                "css_origin": "user", "run_at": "document_start", "all_frames": True})
            elif fix["world"] == "MAIN":
                scripts.append({"matches": matches(domain), "js": [fix["js"]],
                                "world": "MAIN", "run_at": "document_start"})
            else:
                scripts.append({"matches": matches(domain), "js": ["sites.js", "settings.js", fix["js"]],
                                "run_at": "document_start"})
        selectors = sum(len(v) for v in cosmetic.values())
        sites.append({"domain": domain, "key": f"site:{domain}", "ruleset": ruleset_id(domain),
                      "rules": len(rules), "selectors": selectors, "protected": domain in PROTECTED})

    (EXTENSION / "sites.js").write_text(
        "// Generated by tools/build_extension_sites.py from filters/sources/sites; do not edit.\n"
        "// The fansites the extension covers, read by settings.js and the settings page.\n"
        "globalThis.TibiaAntiAdSites = Object.freeze("
        + json.dumps(sites, indent=4).replace("\n]", "\n]") + ");\n",
        encoding="utf-8",
    )

    manifest_path = EXTENSION / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    dnr = manifest["declarative_net_request"]["rule_resources"]
    manifest["declarative_net_request"]["rule_resources"] = [r for r in dnr if not r["id"].startswith("site_")] + rule_resources
    kept = [s for s in manifest["content_scripts"]
            if not any(p.startswith("sites/") for p in s.get("js", []) + s.get("css", []))]
    # settings.js reads the site list, so sites.js loads before it everywhere.
    def with_sites(files):
        files = [f for f in files if f != "sites.js"]
        return files[:files.index("settings.js")] + ["sites.js"] + files[files.index("settings.js"):] if "settings.js" in files else files
    manifest["background"]["scripts"] = with_sites(manifest["background"]["scripts"])
    for script in kept:
        if "js" in script:
            script["js"] = with_sites(script["js"])
        if "settings-bridge.js" in script.get("js", []):
            script["matches"] = [TWITCH_MATCH] + hosts
    manifest["content_scripts"] = kept + scripts
    # The Tibia filter's evidence updates from the repository (tibia-rules.js).
    # Access to every site keeps Safari's toolbar icon tinted on every page (Safari
    # greys it where an extension has no access); content scripts still run only
    # on Twitch and the fansites, and the rule sets match only their hosts.
    manifest["host_permissions"] = [TWITCH_MATCH] + hosts + ["https://raw.githubusercontent.com/*", "<all_urls>"]
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return sites


if __name__ == "__main__":
    for site in build():
        print(f"{site['domain']}: {site['rules']} network rules, {site['selectors']} selectors")
