"""Train the portable statistical model from labelled title/tag observations.

Training requires scikit-learn (tools/model-requirements.txt). Runtime inference
and repository checks require only Python/JavaScript standard libraries.
Predictions previously generated by the filter are never used as labels.
"""
import argparse
import collections
import hashlib
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from twitch_evidence import AUDIT, AUDIT_OTHER, AUDIT_TIBIA, EVIDENCE, features

THRESHOLD = 2.0


def observations():
    result = []
    for row in json.loads(AUDIT.read_text())["classificacao"]:
        label = 1 if row["categoria"] in AUDIT_OTHER else 0 if row["categoria"] in AUDIT_TIBIA else None
        if label is not None:
            result.append({"channel": row["canal"], "title": row["titulo_original"],
                           "tags": [t.strip() for t in row["tags_originais"].split("|") if t.strip()], "label": label})
    return result


def dataset(mode="both"):
    return {row["channel"]: (features(row["title"] if mode != "tags" else "",
                                     row["tags"] if mode != "title" else []), row["label"])
            for row in observations()}


def train(rows):
    # Lazy imports keep inference, normal builds and mocked split checks dependency-free.
    from sklearn.feature_extraction import DictVectorizer
    from sklearn.feature_extraction.text import TfidfTransformer
    from sklearn.linear_model import LogisticRegression

    counts = collections.Counter(feature for values, _ in rows for feature in values)
    vectorizer = DictVectorizer()
    matrix = vectorizer.fit_transform([{key: value for key, value in values.items() if counts[key] >= 2} for values, _ in rows])
    tfidf = TfidfTransformer()
    matrix = tfidf.fit_transform(matrix)
    estimator = LogisticRegression(C=4, class_weight="balanced", fit_intercept=False, max_iter=1000)
    estimator.fit(matrix, [label for _, label in rows])
    factors = {key: value for values, _ in rows for key, value in values.items()}
    weights = {key: [round(float(estimator.coef_[0, i] * tfidf.idf_[i] * factors[key]), 8), round(float(tfidf.idf_[i] * factors[key]), 8)]
               for key, i in sorted(vectorizer.vocabulary_.items())}
    # Zero intercept gives empty/unrecognized text a neutral prior. The fields
    # share learned subwords, so a pattern learned in a tag can inform a title.
    return {"format": "joint-text-logistic-v1", "bias": 0, "threshold": THRESHOLD, "weights": weights}


def score(model, feats):
    known = sorted(set(feats) & model["weights"].keys())
    norm = math.sqrt(sum(model["weights"][key][1] ** 2 for key in known))
    return model["bias"] + (sum(model["weights"][key][0] for key in known) / norm if norm else 0)


def wilson_interval(successes, total):
    """Two-sided 95% Wilson score interval; no estimate without observations."""
    if total == 0:
        return None
    z = 1.959963984540054
    p = successes / total
    denominator = 1 + z * z / total
    center = (p + z * z / (2 * total)) / denominator
    radius = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / denominator
    return max(0, center - radius), min(1, center + radius)


def cross_validate(rows, folds=5):
    keys = sorted(rows)
    # Prefixes distinguish captures, not independent channels. Keep every
    # observation of the same channel on one side of the train/test boundary.
    def channel(key):
        return key.removeprefix("live:").casefold()

    groups = {name: i % folds for i, name in enumerate(sorted({channel(key) for key in keys}))}
    results = []
    for k in range(folds):
        test = [key for key in keys if groups[channel(key)] == k]
        model = train([rows[key] for key in keys if groups[channel(key)] != k])
        results += [(score(model, rows[key][0]), rows[key][1]) for key in test]
    for cut in (1, 1.5, 2):
        tp = sum(1 for s, y in results if s >= cut and y)
        fp = sum(1 for s, y in results if s >= cut and not y)
        pos = sum(y for _, y in results)
        interval = wilson_interval(tp, tp + fp)
        precision = f"{tp / (tp + fp):.3f}" if tp + fp else "unknown"
        confidence = f"[{interval[0]:.4f}, {interval[1]:.4f}]" if interval else "unknown"
        recall = f"{tp / pos:.3f}" if pos else "unknown"
        abstained = sum(-cut < s < cut for s, _ in results)
        print(f"log-odds >= {cut}: precision {precision} ({fp} official hidden; {tp + fp} predicted other), "
              f"95% Wilson CI {confidence}, recall {recall}, abstention {abstained}/{len(results)}")
    return results


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    report = {"source": "audited labelled capture", "source_sha256": hashlib.sha256(AUDIT.read_bytes()).hexdigest(),
              "threshold": THRESHOLD, "evaluation": "development cross-validation grouped by channel; not an independent holdout", "ablations": {}}
    for mode in ("both", "title", "tags"):
        rows = dataset(mode)
        print(f"{mode}: {len(rows)} labelled observations, {sum(y for _, y in rows.values())} other games")
        results = cross_validate(rows)
        tp = sum(s >= THRESHOLD and y == 1 for s, y in results)
        fp = sum(s >= THRESHOLD and y == 0 for s, y in results)
        count = sum(y for _, y in results)
        report["ablations"][mode] = {"observations": len(rows), "other": count, "true_positive": tp,
            "false_positive": fp, "recall": tp / count, "precision": tp / (tp + fp) if tp + fp else None,
            "precision_wilson_95": wilson_interval(tp, tp + fp),
            "abstained": sum(-THRESHOLD < s < THRESHOLD for s, _ in results)}
    if args.write:
        model = train(list(dataset().values()))
        data = {"revision": 2, "_comment": "Learned statistical inference over full titles and tags. No manual name rules or channel features.",
                "training": {"observations": len(dataset()), "source_sha256": report["source_sha256"],
                             "filter_predictions_used": False, "features": "shared words, word pairs and character 3/4/5-grams; FNV-1a identifiers", "min_observations": 2, "char_feature_weight": 0.25, "regularization_c": 4, "normalization": "l2-tfidf"},
                "model": model}
        EVIDENCE.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
        print(f"wrote {len(model['weights'])} learned feature weights")
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
