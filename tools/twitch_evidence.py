"""Metadata-only inference and browser export of the frozen private-server model."""
import argparse
import json
from pathlib import Path
from tibia_private import CONTEXT, OT
from tibia_spans import SpanModel as PrivateModel, PATTERNS, LANGUAGES, SIZE, FEATURES, DOMAIN_SECOND_LEVELS
from tibia_text import LOOKALIKE
import hashlib

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / 'filters/sources/twitch/tibia-evidence.json'
EXTENSION_DATA = ROOT / 'extension/src/tibia-evidence.js'
PRIVATE_MODEL = ROOT / 'research/twitch/model/private-span-model.json'


def browser_data():
    frozen = PRIVATE_MODEL.read_bytes()
    data = json.loads(frozen)
    runtime = {key: data[key] for key in ('format', 'base_private_probability', 'identifier_weights', 'identifier_cutoffs', 'weights', 'calibration', 'hide_threshold')}
    return {'revision': data['revision'], 'model_sha256': hashlib.sha256(frozen).hexdigest(), 'model': runtime,
            'inference': {'features': list(FEATURES), 'context': CONTEXT, 'lookalike': LOOKALIKE,
                          'languages': LANGUAGES, 'hash_size': SIZE,
                          'domain_second_levels': list(DOMAIN_SECOND_LEVELS),
                          'patterns': dict(PATTERNS, ot=OT.pattern)}}


def extension_data(data):
    # ASCII only: Safari may read extension scripts as Latin-1.
    return (
        '// Generated by tools/twitch_evidence.py --write-js from the frozen private model and shared recognition specification. Do not edit.\n'
        f'globalThis.TWITCH_CLEAN_TIBIA_EVIDENCE = {json.dumps(data, ensure_ascii=True, indent=2)};\n'
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('streams', nargs='?')
    parser.add_argument('--evaluate', action='store_true')
    parser.add_argument('--write-js', action='store_true')
    args = parser.parse_args()
    if args.write_js:
        data = browser_data()
        EVIDENCE.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
        EXTENSION_DATA.write_text(extension_data(data))
        return
    if args.evaluate:
        from train_tibia_spans import evaluate
        evaluate()
        return
    if not args.streams:
        parser.error('streams is required')
    model = PrivateModel.load(PRIVATE_MODEL)
    results = []
    capture = json.loads(Path(args.streams).read_text())
    streams = capture["streams"] if isinstance(capture, dict) else capture
    for stream in streams:
        results.append({'channel': stream.get('channel'), **model.predict(stream.get('title') or '', stream.get('tags') or [])})
    print(json.dumps(results, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
