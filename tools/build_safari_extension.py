"""Build the universal Safari app: the host app and its one web extension.

The Xcode project is generated by XcodeGen from extension/browsers/safari/project.yml.
This script stages what the targets need into dist/safari-project, builds with
xcodebuild, then signs both bundles with their entitlements, ad-hoc by default or
with a local development identity.

    python3 tools/build_safari_extension.py
    python3 tools/build_safari_extension.py --sign-identity "Apple Development"
"""
import argparse
import json
import plistlib
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "extension/src"
SAFARI = ROOT / "extension/browsers/safari"
PROJECT_ROOT = ROOT / "dist/safari-project"
# Spotlight and Launchpad skip folders ending in .noindex, so build products
# never show up next to the installed app.
DERIVED = ROOT / "dist/safari-build.noindex"
APP = ROOT / "dist/safari.noindex/Tibia Anti-Ad.app"

BUNDLE_ID = "com.nesleykent.tibiaantiad"
WEB_EXTENSION_ID = BUNDLE_ID + ".Extension"
SWIFT_FOLDERS = ("App", "WebExtension")

# The macOS app icon sizes Xcode expects, as (point size, scale, source pixels).
APP_ICON_SIZES = [(16, 1, 16), (16, 2, 32), (32, 1, 32), (32, 2, 64), (128, 1, 128),
                  (128, 2, 256), (256, 1, 256), (256, 2, 512), (512, 1, 512)]


LSREGISTER = ("/System/Library/Frameworks/CoreServices.framework/Frameworks/"
              "LaunchServices.framework/Support/lsregister")


def run(*args):
    subprocess.run([str(arg) for arg in args], cwd=ROOT, check=True)


def hide_from_system(*apps):
    """Keep build products and backups out of Launchpad, Spotlight and Safari.

    Xcode registers every app it builds with Launch Services, so each copy shows
    up as another Tibia Anti-Ad; only the installed app in /Applications should.
    """
    for app in apps:
        if app.exists():
            subprocess.run([LSREGISTER, "-u", str(app)], check=False)
        folder = app.parent
        folder.mkdir(parents=True, exist_ok=True)
        (folder / ".metadata_never_index").touch()


# --- Signing -----------------------------------------------------------------

def check_identity(identity):
    if identity == "-":
        return
    identities = subprocess.check_output(["security", "find-identity", "-v", "-p", "codesigning"], text=True)
    if not any(identity in line and '"' in line for line in identities.splitlines()):
        raise RuntimeError("Signing identity is not valid. Check Xcode's certificates and the Apple WWDR intermediate certificate.")


def write_entitlements(path, network=False):
    entitlements = {"com.apple.security.app-sandbox": True}
    if network:
        entitlements["com.apple.security.network.client"] = True
    path.write_bytes(plistlib.dumps(entitlements))


# --- Staging -----------------------------------------------------------------

def stage_web_extension(destination):
    # The manifest is used as is: the toolbar button and its popup are the web
    # extension's own action and popup.html.
    shutil.copytree(SOURCE, destination)


def stage_app(destination):
    destination.mkdir(parents=True)
    for state, name in (("active", "StatusActive"), ("inactive", "StatusInactive")):
        shutil.copy2(SOURCE / f"icons/safari-toolbar/{state}-256.png", destination / f"{name}.png")
    icon_set = destination / "Assets.xcassets/AppIcon.appiconset"
    icon_set.mkdir(parents=True)
    images = []
    for points, scale, pixels in APP_ICON_SIZES:
        filename = f"icon-{pixels}.png"
        shutil.copy2(SOURCE / f"icons/{filename}", icon_set / filename)
        images.append({"idiom": "mac", "size": f"{points}x{points}", "scale": f"{scale}x", "filename": filename})
    (icon_set / "Contents.json").write_text(json.dumps({"images": images, "info": {"version": 1, "author": "xcode"}}, indent=2))
    (destination / "Assets.xcassets/Contents.json").write_text(json.dumps({"info": {"version": 1, "author": "xcode"}}))


def stage_project():
    if PROJECT_ROOT.exists():
        shutil.rmtree(PROJECT_ROOT)
    PROJECT_ROOT.mkdir(parents=True)
    for folder in SWIFT_FOLDERS:
        shutil.copytree(SAFARI / folder, PROJECT_ROOT / folder)
    shutil.copy2(SAFARI / "project.yml", PROJECT_ROOT / "project.yml")
    stage_web_extension(PROJECT_ROOT / "Resources/WebExtension")
    stage_app(PROJECT_ROOT / "Resources/App")
    (PROJECT_ROOT / "Generated").mkdir()


# --- Build and verify --------------------------------------------------------

def xcode_build(version):
    run("xcodegen", "generate", "--spec", PROJECT_ROOT / "project.yml", "--project", PROJECT_ROOT, "--quiet")
    run("xcodebuild", "-project", PROJECT_ROOT / "Tibia Anti-Ad.xcodeproj", "-scheme", "Tibia Anti-Ad",
        "-configuration", "Release", "-derivedDataPath", DERIVED, "-destination", "generic/platform=macOS",
        "ARCHS=arm64 x86_64", "ONLY_ACTIVE_ARCH=NO", f"TIBIA_VERSION={version}",
        "-quiet", "build")
    if APP.exists():
        shutil.rmtree(APP)
    shutil.copytree(DERIVED / "Build/Products/Release/Tibia Anti-Ad.app", APP, symlinks=True)
    for name in ("LICENSE", "THIRD_PARTY_NOTICES.md"):
        shutil.copy2(ROOT / name, APP / "Contents/Resources" / name)


def extension_bundles(app):
    """The embedded extensions by bundle identifier."""
    bundles = {}
    for bundle in (app / "Contents/PlugIns").glob("*.appex"):
        info = plistlib.loads((bundle / "Contents/Info.plist").read_bytes())
        bundles[info["CFBundleIdentifier"]] = bundle
    if set(bundles) != {WEB_EXTENSION_ID}:
        raise RuntimeError(f"Expected only the web extension, found: {sorted(bundles)}")
    return bundles


def sign(identity):
    entitlements = PROJECT_ROOT / "Generated"
    write_entitlements(entitlements / "extension.entitlements")
    write_entitlements(entitlements / "host.entitlements", network=True)
    for bundle in extension_bundles(APP).values():
        run("codesign", "--force", "--sign", identity, "--entitlements", entitlements / "extension.entitlements", bundle)
    run("codesign", "--force", "--sign", identity, "--entitlements", entitlements / "host.entitlements", APP)
    run("codesign", "--verify", "--deep", "--strict", APP)


def verify(app):
    web_resources = extension_bundles(app)[WEB_EXTENSION_ID] / "Contents/Resources"
    for original in SOURCE.rglob("*"):
        relative = original.relative_to(SOURCE)
        if original.is_file() and relative.name != "manifest.json" and original.read_bytes() != (web_resources / relative).read_bytes():
            raise RuntimeError(f"Packaged extension resource differs: {relative}")
    for bundle in [app, *extension_bundles(app).values()]:
        info = plistlib.loads((bundle / "Contents/Info.plist").read_bytes())
        binary = bundle / "Contents/MacOS" / info["CFBundleExecutable"]
        architectures = subprocess.check_output(["lipo", "-archs", str(binary)], text=True).split()
        if not {"arm64", "x86_64"}.issubset(architectures):
            raise RuntimeError(f"Expected a universal Mac binary: {binary}")


def remove_build_files():
    """Delete the build cache and staged project (about 1 GB) once the app is installed."""
    for path in (DERIVED, PROJECT_ROOT, APP.parent):
        if path.exists():
            shutil.rmtree(path)


def build(sign_identity="-"):
    if sys.platform != "darwin":
        raise RuntimeError("Building the Safari app requires macOS, full Xcode and XcodeGen.")
    if not shutil.which("xcodegen"):
        raise RuntimeError("XcodeGen is required: brew install xcodegen")
    check_identity(sign_identity)
    version = json.loads((SOURCE / "manifest.json").read_text())["version"]
    stage_project()
    xcode_build(version)
    sign(sign_identity)
    verify(APP)
    hide_from_system(APP, DERIVED / "Build/Products/Release/Tibia Anti-Ad.app")
    return APP


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sign-identity", default="-",
                        help="Local signing identity name or SHA-1; default: ad-hoc (-).")
    print(build(parser.parse_args().sign_identity))
